"""
Unsloth Llama-3.2-Vision Fine-Tuning Script for Food Craft
──────────────────────────────────────────────────────────
Fine-tunes unsloth/Llama-3.2-11B-Vision-Instruct-bnb-4bit on the multimodal
conversational JSONL generated by download_foodcraft_vision_dataset.py.

Requirements (on NVIDIA CUDA GPU machine / Colab / Kaggle / RunPod):
    pip install "unsloth[colab-new] @ git+https://github.com/unslothai/unsloth.git"
    pip install --no-deps xformers trl peft accelerate bitsandbytes
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from PIL import Image


def load_conversation_rows(jsonl_path: Path, max_samples: int | None = None, split: str = "train") -> list[dict]:
    """Load light metadata rows without loading all images into RAM at once."""
    rows: list[dict] = []
    with jsonl_path.open("r", encoding="utf-8") as f:
        for line in f:
            if not line.strip():
                continue
            row = json.loads(line)
            if split != "all" and row.get("split", "train") != split:
                continue
            img_path = Path(row["image_path"])
            if not img_path.exists():
                continue
            rows.append(row)
            if max_samples and len(rows) >= max_samples:
                break
    return rows


def make_lazy_dataset(rows: list[dict], max_dim: int = 896):
    """Build a torch Dataset that loads PIL images lazily per batch to save RAM."""
    from torch.utils.data import Dataset

    class LazyVisionDataset(Dataset):
        def __init__(self, items: list[dict], limit_dim: int):
            self.rows = items
            self.max_dim = limit_dim

        def __len__(self) -> int:
            return len(self.rows)

        def __getitem__(self, idx: int) -> dict:
            row = self.rows[idx]
            img_path = row["image_path"]
            with Image.open(img_path) as im:
                rgb = im.convert("RGB")
                w, h = rgb.size
                if max(w, h) > self.max_dim:
                    scale = self.max_dim / float(max(w, h))
                    rgb = rgb.resize((int(w * scale), int(h * scale)), Image.Resampling.LANCZOS)
                pil_img = rgb.copy()

            messages = []
            for turn in row["messages"]:
                new_content = []
                for block in turn["content"]:
                    if block.get("type") == "image":
                        new_content.append({"type": "image", "image": pil_img})
                    else:
                        new_content.append({"type": "text", "text": block["text"]})
                messages.append({"role": turn["role"], "content": new_content})

            return {"messages": messages}

    return LazyVisionDataset(rows, max_dim)


def main() -> None:
    parser = argparse.ArgumentParser(description="Fine-tune Llama 3.2 Vision on Food Craft data with Unsloth")
    parser.add_argument(
        "--jsonl",
        type=Path,
        default=Path(__file__).resolve().parent.parent / "data" / "unsloth_foodcraft" / "train_conversations.jsonl",
        help="Path to train_conversations.jsonl",
    )
    parser.add_argument("--model-name", default="unsloth/Llama-3.2-11B-Vision-Instruct-bnb-4bit")
    parser.add_argument("--output-dir", default="outputs/foodcraft-llama32-vision-lora")
    parser.add_argument("--max-steps", type=int, default=500)
    parser.add_argument("--epochs", type=int, default=1)
    parser.add_argument("--batch-size", type=int, default=2)
    parser.add_argument("--grad-accum", type=int, default=8)
    parser.add_argument("--lr", type=float, default=2e-4)
    parser.add_argument("--max-samples", type=int, default=None)
    args = parser.parse_args()

    import torch

    if not torch.cuda.is_available():
        print(
            "ERROR: No NVIDIA CUDA GPU detected on this machine.\n"
            "Unsloth requires an NVIDIA GPU (>=12 GB VRAM for Llama-3.2-11B-Vision 4-bit).\n"
            "Copy D:\\Food Craft\\data\\unsloth_foodcraft and this script to Colab/Kaggle/RunPod/GPU server and run:\n"
            f"  python {Path(__file__).name} --jsonl path/to/train_conversations.jsonl",
            file=sys.stderr,
        )
        sys.exit(1)

    if not args.jsonl.exists():
        print(f"ERROR: Dataset JSONL not found: {args.jsonl}", file=sys.stderr)
        sys.exit(1)

    from trl import SFTConfig, SFTTrainer
    from unsloth import FastVisionModel, is_bf16_supported
    from unsloth.trainer import UnslothVisionDataCollator

    print(f"Loading rows from {args.jsonl} ...")
    rows = load_conversation_rows(args.jsonl, max_samples=args.max_samples, split="train")
    if not rows:
        print("ERROR: No valid training rows found.", file=sys.stderr)
        sys.exit(1)
    print(f"Loaded {len(rows):,} training image-conversation samples.")

    train_dataset = make_lazy_dataset(rows)

    print(f"Loading {args.model_name} ...")
    model, tokenizer = FastVisionModel.from_pretrained(
        args.model_name,
        load_in_4bit=True,
        use_gradient_checkpointing="unsloth",
    )

    model = FastVisionModel.get_peft_model(
        model,
        finetune_vision_layers=True,
        finetune_language_layers=True,
        finetune_attention_modules=True,
        finetune_mlp_modules=True,
        r=16,
        lora_alpha=16,
        lora_dropout=0,
        bias="none",
        random_state=3407,
        use_rslora=False,
    )

    FastVisionModel.for_training(model)

    trainer = SFTTrainer(
        model=model,
        tokenizer=tokenizer,
        train_dataset=train_dataset,
        data_collator=UnslothVisionDataCollator(model, tokenizer),
        args=SFTConfig(
            per_device_train_batch_size=args.batch_size,
            gradient_accumulation_steps=args.grad_accum,
            warmup_steps=20,
            max_steps=args.max_steps if args.max_steps > 0 else -1,
            num_train_epochs=args.epochs,
            learning_rate=args.lr,
            fp16=not is_bf16_supported(),
            bf16=is_bf16_supported(),
            logging_steps=5,
            save_steps=100,
            optim="adamw_8bit",
            weight_decay=0.01,
            lr_scheduler_type="linear",
            seed=3407,
            output_dir=args.output_dir,
            report_to="none",
            remove_unused_columns=False,
            dataset_text_field="",
            dataset_kwargs={"skip_prepare_dataset": True},
            max_seq_length=2048,
        ),
    )

    trainer.train()

    save_dir = Path(args.output_dir) / "final_lora"
    model.save_pretrained(str(save_dir))
    tokenizer.save_pretrained(str(save_dir))
    print(f"Saved fine-tuned Llama-3.2-Vision LoRA adapter to {save_dir}")


if __name__ == "__main__":
    main()
